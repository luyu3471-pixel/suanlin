"""Browser QA and actual screenshots; build tools only, not runtime dependencies."""
from pathlib import Path
import json
import os
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'.tools'))
os.environ.setdefault('PLAYWRIGHT_BROWSERS_PATH',str(ROOT/'.tools'/'browsers'))
from playwright.sync_api import sync_playwright

def run(url='http://127.0.0.1:8765'):
    out=ROOT/'results'/'screenshots';out.mkdir(parents=True,exist_ok=True)
    errors=[];checks=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=str(ROOT/'.tools/browsers/chromium-1248/chrome-win64/chrome.exe'),headless=True,args=['--no-proxy-server'])
        page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(url,wait_until='networkidle')
        page.get_by_role('heading',name='协同工作台',exact=True).wait_for()
        checks.append('overview loads with live API')
        page.wait_for_timeout(950)
        page.screenshot(animations='disabled',path=str(out/'overview.png'),full_page=True)
        page.get_by_role('button',name='创建任务',exact=True).click()
        page.locator('[name="name"]').fill('浏览器验收任务')
        page.locator('[name="events"]').fill('消防出口被纸箱堵塞\n配电箱发现浓烟和明火')
        page.get_by_role('button',name='提交任务').click()
        page.locator('#create-dialog').wait_for(state='hidden')
        page.wait_for_timeout(1800)
        page.goto(url + '/#tasks')
        page.get_by_role('heading',name='任务中心',exact=True).wait_for()
        page.locator('#task-search').fill('浏览器验收任务')
        page.get_by_role('button',name='查看 ↗').first.click()
        page.locator('#detail-dialog').wait_for(state='visible')
        page.get_by_text('通道占用',exact=True).wait_for()
        page.get_by_text('烟雾风险',exact=True).wait_for()
        page.wait_for_timeout(950)
        page.screenshot(animations='disabled',path=str(out/'task-detail.png'),full_page=True)
        checks.append('create, execute, search and inspect two real classifier outputs')
        page.get_by_role('button',name='关闭',exact=True).last.click()
        page.goto(url + '/#nodes')
        page.get_by_role('heading',name='算力节点',exact=True).wait_for()
        page.get_by_role('button',name='暂停接收任务').first.click()
        page.get_by_role('button',name='恢复接收任务').wait_for()
        page.get_by_role('button',name='恢复接收任务').click()
        page.wait_for_timeout(300)
        page.add_style_tag(content='.node-details div:nth-child(2) b{font-size:0!important}.node-details div:nth-child(2) b::after{content:"主机信息已隐藏";font-size:13px}')
        page.wait_for_timeout(950)
        page.screenshot(animations='disabled',path=str(out/'nodes.png'),full_page=True)
        checks.append('node drain and resume persisted through API')
        page.goto(url + '/#experiments')
        page.get_by_role('heading',name='对比实验',exact=True).wait_for()
        page.get_by_role('button',name='受限带宽',exact=True).click()
        page.get_by_text('当前条件：受限带宽。',exact=False).wait_for()
        page.wait_for_timeout(950)
        page.screenshot(animations='disabled',path=str(out/'experiments.png'),full_page=True)
        checks.append('simulation results and condition switch')
        page.goto(url + '/#guide')
        page.get_by_role('heading',name='部署与验证',exact=True).wait_for()
        checks.append('deployment instructions load')
        with page.expect_download() as download:
            page.goto(url + '/#tasks')
            page.get_by_role('button',name='导出记录',exact=False).click()
        download.value.save_as(str(ROOT/'results'/'ui_export.csv'))
        checks.append('CSV downloaded through UI')
        page.set_viewport_size({'width':390,'height':844})
        page.goto(url + '/#overview')
        page.get_by_role('heading',name='协同工作台',exact=True).wait_for()
        page.wait_for_timeout(950)
        page.screenshot(animations='disabled',path=str(out/'mobile.png'),full_page=True)
        overflow=page.evaluate('document.documentElement.scrollWidth>window.innerWidth')
        if overflow:errors.append('mobile horizontal overflow')
        checks.append('390px mobile layout without body overflow' if not overflow else 'mobile layout needs repair')
        browser.close()
    (ROOT/'results'/'browser_qa.json').write_text(json.dumps({'checks':checks,'errors':errors,'passed':not errors},ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'checks':len(checks),'errors':errors},ensure_ascii=True))
    if errors:raise SystemExit(1)

if __name__=='__main__':run()
